// Command eval compares gateway model aliases (fast vs smart) on profile and
// fact extraction over the golden fixtures, and writes a markdown report.
//
// It calls the extractor directly (no upload, no Tika) so the numbers measure
// the model, not the rest of the pipeline.
package main

import (
	"context"
	"flag"
	"fmt"
	"log"
	"os"
	"path/filepath"
	"strings"
	"time"

	"github.com/imssuthar/jobmatcher/services/core/internal/evalkit"
	"github.com/imssuthar/jobmatcher/services/core/internal/llm"
	"github.com/imssuthar/jobmatcher/services/core/internal/profile"
)

type row struct {
	model, fixture           string
	ok                       bool
	errMsg                   string
	profileSecs, factsSecs   float64
	attempts                 int
	tokens                   int
	skillRecall, skillGround float64
	companyRecall            float64
	facts                    int
	numberGround             float64
	missing                  []string
}

func main() {
	models := flag.String("models", "fast,smart", "comma-separated gateway aliases to compare")
	flag.Parse()

	dir := env("FIXTURES_DIR", "../../testdata/fixtures")
	golden, err := evalkit.Load(dir)
	if err != nil {
		log.Fatal(err)
	}
	client := llm.New(env("LITELLM_URL", "http://localhost:4000"), env("LITELLM_KEY", "sk-jobmatcher-local"), 10*time.Minute)

	var rows []row
	for _, m := range strings.Split(*models, ",") {
		x := &profile.Extractor{LLM: client, ProfileModel: m, FactsModel: m, MaxRetries: 2}
		for _, f := range golden.Fixtures {
			fmt.Printf("evaluating %-6s on %s ...\n", m, f.ID)
			rows = append(rows, evalOne(x, golden, f, m))
		}
	}

	report := render(rows)
	fmt.Println()
	fmt.Println(report)
	out := filepath.Join(env("REPORT_DIR", "../../docs/experiments"), "phase1-extraction-models.md")
	if err := os.WriteFile(out, []byte(report), 0o644); err != nil {
		log.Fatal(err)
	}
	fmt.Println("report written to", out)
}

func evalOne(x *profile.Extractor, g *evalkit.Golden, f evalkit.Fixture, model string) row {
	ctx := context.Background()
	r := row{model: model, fixture: f.ID}
	src, err := g.SourceText(f)
	if err != nil {
		r.errMsg = err.Error()
		return r
	}

	start := time.Now()
	p, pu, err := x.ExtractProfile(ctx, src)
	r.profileSecs = time.Since(start).Seconds()
	r.attempts, r.tokens = pu.Attempts, pu.PromptTokens+pu.CompletionTokens
	if err != nil {
		r.errMsg = err.Error()
		return r
	}
	start = time.Now()
	fd, fu, err := x.ExtractFacts(ctx, src, p)
	r.factsSecs = time.Since(start).Seconds()
	r.attempts += fu.Attempts
	r.tokens += fu.PromptTokens + fu.CompletionTokens
	if err != nil {
		r.errMsg = err.Error()
		return r
	}

	r.ok = true
	r.skillRecall, r.missing = evalkit.Recall(f.Skills, p.Skills)
	r.skillGround, _ = evalkit.GroundedRate(src, p.Skills)
	companies := make([]string, 0, len(p.Experience))
	for _, e := range p.Experience {
		companies = append(companies, e.Company)
	}
	r.companyRecall, _ = evalkit.Recall(f.Companies, companies)
	texts := make([]string, len(fd.Facts))
	for i, it := range fd.Facts {
		texts[i] = it.Text
	}
	r.facts = len(fd.Facts)
	r.numberGround = profile.NumberGrounding(src, texts).Rate()
	return r
}

func render(rows []row) string {
	var b strings.Builder
	fmt.Fprintf(&b, "# Phase 1 experiment: extraction quality by model\n\n")
	fmt.Fprintf(&b, "Generated by `make eval-phase1` on %s. Temperature 0, seed 42, schema-constrained JSON, up to 2 correction retries.\n\n", time.Now().Format("2006-01-02"))
	fmt.Fprintf(&b, "- **Skill recall**: share of the golden skills that were extracted.\n")
	fmt.Fprintf(&b, "- **Skill grounding**: share of extracted skills that literally appear in the resume (low = invented skills).\n")
	fmt.Fprintf(&b, "- **Number grounding**: share of numbers in facts that appear in the resume (low = invented metrics).\n\n")
	fmt.Fprintf(&b, "| Model | Fixture | Profile s | Facts s | Attempts | Tokens | Skill recall | Skill grounding | Companies | Facts | Number grounding |\n")
	fmt.Fprintf(&b, "|---|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|\n")
	type agg struct {
		secs, recall, ground, num float64
		n, fails                  int
	}
	sums := map[string]*agg{}
	var order []string
	for _, r := range rows {
		a, ok := sums[r.model]
		if !ok {
			a = &agg{}
			sums[r.model] = a
			order = append(order, r.model)
		}
		if !r.ok {
			a.fails++
			fmt.Fprintf(&b, "| %s | %s | %.0f | %.0f | %d | %d | failed: %s | | | | |\n", r.model, r.fixture, r.profileSecs, r.factsSecs, r.attempts, r.tokens, trunc(r.errMsg, 60))
			continue
		}
		a.n++
		a.secs += r.profileSecs + r.factsSecs
		a.recall += r.skillRecall
		a.ground += r.skillGround
		a.num += r.numberGround
		fmt.Fprintf(&b, "| %s | %s | %.0f | %.0f | %d | %d | %.0f%% | %.0f%% | %.0f%% | %d | %.0f%% |\n",
			r.model, r.fixture, r.profileSecs, r.factsSecs, r.attempts, r.tokens,
			r.skillRecall*100, r.skillGround*100, r.companyRecall*100, r.facts, r.numberGround*100)
	}
	fmt.Fprintf(&b, "\n## Summary\n\n| Model | Avg seconds per resume | Avg skill recall | Avg skill grounding | Avg number grounding | Failures |\n|---|---:|---:|---:|---:|---:|\n")
	for _, m := range order {
		a := sums[m]
		if a.n == 0 {
			fmt.Fprintf(&b, "| %s | – | – | – | – | %d |\n", m, a.fails)
			continue
		}
		n := float64(a.n)
		fmt.Fprintf(&b, "| %s | %.0f | %.0f%% | %.0f%% | %.0f%% | %d |\n", m, a.secs/n, a.recall/n*100, a.ground/n*100, a.num/n*100, a.fails)
	}
	return b.String()
}

func env(k, def string) string {
	if v := os.Getenv(k); v != "" {
		return v
	}
	return def
}

func trunc(s string, n int) string {
	if len(s) <= n {
		return s
	}
	return s[:n] + "…"
}
